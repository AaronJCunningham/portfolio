"""Restore the mapped NKZ road passage without changing the approved city data.

Run with .cache/berlin-mitte/venv/bin/python (the existing Shapely environment).
OSM way 65425836: tunnel=building_passage, maxheight=4, two traffic lanes.
https://www.openstreetmap.org/way/65425836
"""
import gzip
import json
import math
from pathlib import Path
from shapely.geometry import LineString, Polygon

ROOT = Path(__file__).resolve().parents[1] / 'public/experiments/berlin'
data = json.loads(gzip.decompress((ROOT / 'data/berlin.json.gz').read_bytes()))
road = next(r for r in data['roads'] if r['id'] == 'w65425836')
a, b = road['pts'][:2], road['pts'][-2:]
dx, dz = b[0] - a[0], b[1] - a[1]
length = math.hypot(dx, dz)
# Include the separately mapped sidewalks and reach through both facade skins.
corridor = LineString([(a[0] - dx / length * 3, a[1] - dz / length * 3),
                       (b[0] + dx / length * 3, b[1] + dz / length * 3)]).buffer(road['width'] / 2 + 2.5, cap_style=2)
parts = {}
for source_id in ['lod2:DEBE3Df39BZhuunM:0', 'lod2:DEBE00YY1IW0004t:0']:
    source = next(s for s in data['buildings'] if s['id'] == source_id)
    polygon = Polygon(list(zip(source['ring'][::2], source['ring'][1::2])))
    parts[source_id] = []
    for geometry, base in [(polygon.difference(corridor), 0), (polygon.intersection(corridor), 4.25)]:
        polygons = list(geometry.geoms) if geometry.geom_type == 'MultiPolygon' else [geometry]
        for p in polygons:
            assert p.is_valid and not p.interiors
            parts[source_id].append({'ring': [round(v, 4) for point in list(p.exterior.coords)[:-1] for v in point], 'minHeight': base})
    assert abs(sum(Polygon(list(zip(p['ring'][::2], p['ring'][1::2]))).area for p in parts[source_id]) - polygon.area) < 0.02

(ROOT / 'js/building-passage-data.js').write_text(
    '// Generated by scripts/prepare-adalbert-passage.py. Berlin LoD2 (DL-DE-Zero-2.0), OSM (ODbL-1.0).\n'
    'export const ADALBERT_PASSAGE_PARTS = ' + json.dumps(parts, separators=(',', ':')) + ';\n')
